def export(key, folder, title, build, anims):
    m, img, gl = build(); A, T = anims()
    ident = key
    geo = geo_json(f"geometry.{ident}", m, 128, 128)
    base = f"{folder}/{title}"
    W(f"{base}/{key}.geo.json", geo)
    W(f"{base}/{key}.animation.json", anim_json(ident, A))
    W(f"{base}/{key}.bbmodel", bbmodel(key, m.bones, m.cubes, img, 128, 128, A))
    SAVE(img, f"{base}/{key}.png"); SAVE(gl, f"{base}/{key}_glowing.png")
    W(f"{base}/{key}_animation_timings.json", {"note": "Seconds. Use for server/client attack timing sync; animation names are exact.",
                                               "animation_ids": [f"animation.{ident}.{n}" for n in A], "timings": T})
    views = [render(m.cubes, img, gl, yaw=y, pitch=p, size=560) for y, p in ((-32, 18), (-90, 8), (148, 18))]
    pv = Image.new("RGB", (1680, 560)); [pv.paste(v, (i * 560, 0)) for i, v in enumerate(views)]
    SAVE(pv, f"{base}/{key}_preview.png")
    SAVE(views[0].resize((256, 256)), f"{base}/{key}_icon.png")
    print(key, len(m.cubes), "cubes", len(m.bones), "bones", len(A), "anims", img.size)
    return m


