S = lambda x: math.sin(2 * math.pi * x)


def cyc(L, n, f): return {round(L * i / n, 3): [round(float(x), 2) for x in f(i / n)] for i in range(n + 1)}
def kf(d): return {float(t): [float(x) for x in v] for t, v in d.items()}
def an(L, loop, spec): return {"L": L, "loop": loop, "b": {b: {c: kf(k) for c, k in chs.items()} for b, chs in spec.items()}}
